/**
 * ヒント本文の整形。
 *
 * 実 LLM で次のような出力が返った。
 *
 * ```
 * Lv2: その変数がどこから来ているか（props・state・フック）を上流に向かってたどり…
 * ```
 *
 * **画面は既に「Lv2」をバッジとして表示している**ため、本文にも入ると二重になる。
 * 原因は Diagnoser のプロンプトで、出力例そのものが `"Lv1: 着目範囲を狭めるヒント"` と
 * 書かれていた。**モデルは例を忠実に真似ただけ**である。
 *
 * プロンプト側は直したが、生成物の整形は決定的に行う。
 * 表示の体裁を確率的な指示に委ねない。
 */

/**
 * 先頭のレベル表記を落とす。`Lv2:` / `Lv2：` / `レベル2.` / `[Lv2]` などを想定する。
 *
 * **本文の途中に現れる「Lv3」は残す。**
 * 「`X of undefined` は…」のような一般化された知識の説明で、
 * 段階に言及すること自体は正当だから。
 */
export function stripHintLabel(text: string): string {
  return text.replace(LEVEL_LABEL, '').trim()
}

/**
 * 括弧で囲まれていれば区切り記号は任意、素の表記なら区切り記号を必須にする。
 *
 * 素の `Lv3` で区切りを任意にすると、**「Lv3 のヒントと同じ枠組みです」のような
 * 正当な本文の冒頭まで削ってしまう。** 「ラベルとして書かれている」と言えるのは、
 * 囲まれているか、区切り記号が続いている場合だけ。
 */
const LEVEL_LABEL =
  /^\s*(?:[[（(]\s*(?:Lv|LV|lv|レベル|Level)\s*\d+\s*[\])）]\s*[:：.．、,-]?|(?:Lv|LV|lv|レベル|Level)\s*\d+\s*[:：.．、,-])\s*/u
